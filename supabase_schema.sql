-- =========================================================================
-- TI AUTOPILOT - Trade Execution Ledger Table Schema for Supabase (PostgreSQL)
-- Run this script in your Supabase Project -> SQL Editor -> New Query -> Run
-- =========================================================================

CREATE TABLE IF NOT EXISTS public.trade_ledger (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket BIGINT UNIQUE NOT NULL,
  strategy TEXT NOT NULL,
  symbol TEXT NOT NULL,
  action TEXT NOT NULL,                      -- 'BUY' or 'SELL'
  lot NUMERIC(10, 2) NOT NULL,
  open_price NUMERIC(15, 5) NOT NULL,
  close_price NUMERIC(15, 5),
  sl NUMERIC(15, 5) NOT NULL,
  tp NUMERIC(15, 5) NOT NULL,
  profit_loss NUMERIC(12, 2) DEFAULT 0.0,
  profit_loss_pct NUMERIC(8, 2) DEFAULT 0.0,
  equity_after_trade NUMERIC(15, 2) NOT NULL, -- Where equity stands after every trade
  balance_after_trade NUMERIC(15, 2) NOT NULL,
  status TEXT DEFAULT 'OPEN',                -- 'OPEN' or 'CLOSED'
  open_time TIMESTAMPTZ DEFAULT NOW(),
  close_time TIMESTAMPTZ,
  comment TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Indices for rapid querying
CREATE INDEX IF NOT EXISTS idx_supabase_ledger_ticket ON public.trade_ledger(ticket);
CREATE INDEX IF NOT EXISTS idx_supabase_ledger_status ON public.trade_ledger(status);
CREATE INDEX IF NOT EXISTS idx_supabase_ledger_close_time ON public.trade_ledger(close_time DESC);

-- Enable Row Level Security (RLS)
ALTER TABLE public.trade_ledger ENABLE ROW LEVEL SECURITY;

-- Allow public read access (for dashboards and client reporting)
CREATE POLICY "Allow public read access to trade ledger"
  ON public.trade_ledger FOR SELECT
  USING (true);

-- Allow authenticated / service role insert and update
CREATE POLICY "Allow service role insert and update"
  ON public.trade_ledger FOR ALL
  USING (true)
  WITH CHECK (true);
